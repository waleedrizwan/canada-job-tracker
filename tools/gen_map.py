"""Generates src/canada_map.rs: SVG paths for Canada's provinces and territories.

Input is Natural Earth's public-domain 1:50m admin-1 boundaries:
  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson

Usage: python3 tools/gen_map.py path/to/ne_50m_admin_1_states_provinces.geojson > src/canada_map.rs

Projection is Lambert conformal conic with Statistics Canada's parameters
(standard parallels 49°N and 77°N, central meridian 91°52'W), so the map looks
the way Canadians are used to seeing it.
"""

import json
import math
import sys

WIDTH = 800.0
PAD = 6.0
TOLERANCE = 0.7    # Douglas-Peucker tolerance, in output pixels
MIN_AREA = 6.0     # drop islands smaller than this many square pixels

PHI1, PHI2 = math.radians(49), math.radians(77)
PHI0, LAM0 = math.radians(63.390675), math.radians(-91.866667)
N = math.log(math.cos(PHI1) / math.cos(PHI2)) / math.log(
    math.tan(math.pi / 4 + PHI2 / 2) / math.tan(math.pi / 4 + PHI1 / 2))
F = math.cos(PHI1) * math.tan(math.pi / 4 + PHI1 / 2) ** N / N
RHO0 = F / math.tan(math.pi / 4 + PHI0 / 2) ** N

CODES = {"AB", "BC", "MB", "NB", "NL", "NS", "NT", "NU", "ON", "PE", "QC", "SK", "YT"}


def project(lon, lat):
    phi, lam = math.radians(lat), math.radians(lon)
    rho = F / math.tan(math.pi / 4 + phi / 2) ** N
    theta = N * (lam - LAM0)
    return rho * math.sin(theta), RHO0 - rho * math.cos(theta)


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy) or 1e-9
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / norm
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]


def simplify_ring(ring, tol):
    """Closed rings have identical ends, so split at the point farthest from the start first."""
    pts = ring[:-1] if ring[0] == ring[-1] else ring
    if len(pts) < 4:
        return pts
    x0, y0 = pts[0]
    far = max(range(len(pts)), key=lambda i: (pts[i][0] - x0) ** 2 + (pts[i][1] - y0) ** 2)
    a = simplify(pts[: far + 1], tol)
    b = simplify(pts[far:] + [pts[0]], tol)
    return a[:-1] + b[:-1]


def area(pts):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(pts, pts[1:] + pts[:1]))) / 2


def main(path):
    features = [f for f in json.load(open(path, encoding="utf-8"))["features"]
                if f["properties"].get("adm0_a3") == "CAN" and f["properties"].get("postal") in CODES]
    shapes = {}
    for f in features:
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        # Outer rings only; holes are lakes and too small to matter at this scale.
        shapes[f["properties"]["postal"]] = [[project(lon, lat) for lon, lat in poly[0]] for poly in polys]

    xs = [x for rings in shapes.values() for r in rings for x, _ in r]
    ys = [y for rings in shapes.values() for r in rings for _, y in r]
    scale = (WIDTH - 2 * PAD) / (max(xs) - min(xs))
    height = (max(ys) - min(ys)) * scale + 2 * PAD
    fit = lambda p: ((p[0] - min(xs)) * scale + PAD, (max(ys) - p[1]) * scale + PAD)

    out = []
    for code in sorted(shapes):
        d, biggest, label = [], 0.0, (0.0, 0.0)
        for ring in shapes[code]:
            pts = simplify_ring([fit(p) for p in ring], TOLERANCE)
            a = area(pts)
            if a < MIN_AREA or len(pts) < 4:
                continue
            if a > biggest:
                biggest = a
                label = (sum(x for x, _ in pts) / len(pts), sum(y for _, y in pts) / len(pts))
            d.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
        out.append((code, "".join(d), label))

    print("// Generated by tools/gen_map.py from Natural Earth 1:50m admin-1 boundaries (public domain).")
    print("// Do not edit by hand.")
    print()
    print(f"pub const VIEW_W: f64 = {WIDTH:.0f}.0;")
    print(f"pub const VIEW_H: f64 = {height:.1f};")
    print()
    print("/// (province code, SVG path, label anchor x, label anchor y)")
    print(f"pub const PROVINCES: [(&str, &str, f64, f64); {len(out)}] = [")
    for code, d, (lx, ly) in out:
        print(f'    ("{code}", "{d}", {lx:.1f}, {ly:.1f}),')
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
